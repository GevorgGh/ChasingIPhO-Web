interface I18nContextType {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: string) => string;
  translateTopic: (topicKey: string) => string;
}

const I18nContext = createContext<I18nContextType>({
  lang: "en",
  setLang: () => {},
  t: (key: string) => key,
  translateTopic: (key: string) => key,
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    const stored = localStorage.getItem("chasing-ipho-lang") as Lang | null;
    if (stored && ["en", "hy", "ru"].includes(stored)) {
      setLangState(stored);
    }
  }, []);

  const setLang = (newLang: Lang) => {
    setLangState(newLang);
    localStorage.setItem("chasing-ipho-lang", newLang);
  };

  const t = (key: string) => TEXTS[lang]?.[key] ?? TEXTS.en[key] ?? key;

  const translateTopic = (topicKey: string) => {
    const clean = topicKey?.trim().toLowerCase() || "general";
    return TOPIC_TRANSLATIONS[clean]?.[lang] ?? topicKey?.replace(/_/g, " ").replace(/\b\w/g, c => c.toUpperCase()) ?? "General";
  };

  return (
    <I18nContext.Provider value={{ lang, setLang, t, translateTopic }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}
